-- =====================================================================
-- V17 · The third Model 2 classifier: communication and collaboration
--
-- Over-budget and requirement-change both ask whether the plan was
-- wrong. This one asks whether the team is still working as one, which
-- is a different failure and usually the upstream one — a sprint where
-- nobody is talking produces the overrun and the churn a fortnight
-- later, and by then both of the other two models have caught it.
--
-- Five readings, all measured from what the app already records rather
-- than asked of the team: how long a comment waits for a reply from
-- somebody else, how much gets written per task, how many elapsed days
-- have nothing on them at all, how many tasks are blocked, and how many
-- came back after being called done. A survey field would have been
-- cheaper and would have measured whoever filled it in.
--
-- The model is a DistilBERT classifier fine-tuned on a synthetic corpus
-- of those five readings rendered as one sentence. Synthetic because
-- there is no observational dataset here to be had: no sprint's history
-- carries a column saying it failed because the team stopped
-- communicating. The labels come from a deterministic composite over
-- the same five readings — which means the equation is not an
-- approximation of the classifier, it IS the boundary the classifier
-- was fitted to, and the service falls back to it when the weights are
-- absent. Every response says which of the two answered.
--
-- What the transformer adds over the equation is tolerance, not a
-- second opinion: the composite is a stack of step functions, so a
-- sprint at 7 is Medium and one at 8 is High with nothing between. The
-- fine-tune learns the shape of those edges and answers with a
-- distribution, which is what lets a near-boundary sprint read as
-- near-boundary.
--
-- No accuracy figures are recorded in the metadata, and their absence
-- is the honest reading rather than an oversight. Held-out accuracy
-- against a corpus generated by the same function you are being scored
-- against measures memorisation of an equation, not prediction of
-- anything, and putting 0.99 on the admin screen would be the single
-- most misleading number in this schema.
-- =====================================================================

-- Widen the risk type. Recreated rather than altered: Postgres has no
-- ALTER ... CHECK, and dropping first keeps the intent legible in the
-- diff instead of hiding a new value inside a rewritten constraint.
ALTER TABLE risk_assessments DROP CONSTRAINT IF EXISTS ck_risk_type;
ALTER TABLE risk_assessments ADD CONSTRAINT ck_risk_type
    CHECK (risk_type IN ('OVER_BUDGET', 'REQUIREMENT_CHANGE', 'COMMUNICATION_COLLABORATION'));

COMMENT ON COLUMN risk_assessments.risk_type IS
    'OVER_BUDGET | REQUIREMENT_CHANGE | COMMUNICATION_COLLABORATION';

-- The registry row. Gated by ai.risk alongside its two siblings: a
-- workspace switches off *risk assessment*, not one classifier of three.
--
-- The latency budget is 8s rather than the 3s the other two get. A
-- transformer forward pass on CPU is a different cost from a CatBoost
-- score, and a budget the model cannot meet would mark every healthy
-- prediction DEGRADED — which is worse than no budget, because it
-- teaches everyone to ignore the flag.
INSERT INTO ai_models (code, name, description, version, task_type, default_mode,
                       latency_budget_ms, endpoint_url, metadata)
VALUES ('M2_COMMUNICATION_COLLABORATION',
        'Communication & Collaboration Risk Classifier',
        'Predicts the probability that a sprint''s coordination — reply latency, '
        'written discussion, silent days, blockers and rework — is what puts it at risk.',
        '1.0.0', 'CLASSIFICATION', 'FINE_TUNED', 8000,
        'http://localhost:8000/predict/risk/communication-collaboration',
        jsonb_build_object(
            'threshold', 0.5,
            'outputUnit', 'probability',
            'target', 'sprint coordination breaking down',
            'modelType', 'DistilBERT (3-class), with the composite equation it was '
                         'trained on as a fallback when the weights are absent',
            'features', jsonb_build_array('avg_response_time', 'comments_per_task',
                                          'inactive_days', 'blockers', 'reopened_tasks'),
            'compositeRange', '0..18',
            'severityScale', jsonb_build_array('Low', 'Medium', 'High'),
            'trainedOn', 'synthetic, balanced 1000/class by rejection sampling',
            -- Said plainly, because a reader who assumed otherwise would trust this
            -- model for exactly the wrong reason.
            'knownLimitation', 'labels are synthetic — this model encodes an agreed '
                               'definition of poor collaboration, not an observed '
                               'relationship between collaboration and sprint outcomes. '
                               'Treat a High as a well-argued flag, not as evidence.'))
ON CONFLICT (code) DO NOTHING;
